ORDER = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-!:"
GLNAME = {'-': 'GL_DASH', '!': 'GL_BANG', ':': 'GL_COLON'}

for i, ch in enumerate(ORDER):
    print("%-10s equ %d" % (GLNAME.get(ch, "GL_%s" % ch), i))
print("%-10s equ %d" % ("GL_SPACE", 0xFE))
print("%-10s equ %d" % ("GL_END", 0xFF))
print("%-10s equ %d" % ("FONT_W", 5))
print("%-10s equ %d" % ("FONT_H", 7))

#  The font goes out as a binary too, for the same reason as the sine: it
#  is never written to, and the code bank has better uses for 273 bytes.
font = bytearray()
for ch in ORDER:
    rows = FONT[ch].split()
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
    font += bytes(int(r, 2) for r in rows)
open(os.path.join(outdir, "font.raw"), "wb").write(font)

