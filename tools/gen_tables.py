#!/usr/bin/env python3
# ============================================================================
#  gen_tables.py — build-time tables (stdout -> build/tables.inc).
#
#    sin_table  signed sine, one full turn in 256 steps, amplitude 127.
#               Page aligned, so a lookup is "ld l,angle / ld h,page".
#               cos(a) = sin[(a + 64) AND 255].
#    font5x7    36 glyphs (0-9, A-Z) plus a few marks, 7 bytes each, one
#               per row, bit 4 = leftmost pixel. Used by the status strip
#               and the between-level banners.
#    strings    the handful of words the game says, as glyph indices.
# ============================================================================
import math
